//! Two bitmap faces: a 3x5 for the resting text and a 5x7 for overlay words. Caps only; input is upcased.
//! The glyphs are spelled out in this file; no font file was ever imported.

use crate::frame::{Frame, Rgb};

pub struct Font {
    pub w: i32,
    pub h: i32,
    /// Advance for a space; narrower than a glyph so `FABLE XHIGH` fits the main area.
    space: i32,
    glyphs: &'static [(char, &'static [&'static str])],
}

impl Font {
    fn glyph(&self, ch: char) -> Option<&'static [&'static str]> {
        let ch = ch.to_ascii_uppercase();
        self.glyphs.iter().find(|(c, _)| *c == ch).map(|(_, rows)| *rows)
    }

    /// Whether every character of `s` has a glyph (a missing one would silently draw as a gap).
    pub fn covers(&self, s: &str) -> bool {
        s.chars().all(|ch| ch == ' ' || self.glyph(ch).is_some())
    }

    pub fn width(&self, s: &str) -> i32 {
        let mut n = 0;
        for ch in s.chars() {
            n += if ch == ' ' { self.space } else { self.w + 1 };
        }
        (n - 1).max(0)
    }

    /// Draws `s` with its top-left at (x, y); returns the x just past the last glyph.
    pub fn draw(&self, f: &mut Frame, s: &str, mut x: i32, y: i32, c: Rgb) -> i32 {
        for ch in s.chars() {
            if ch == ' ' {
                x += self.space;
                continue;
            }
            if let Some(rows) = self.glyph(ch) {
                for (r, row) in rows.iter().enumerate() {
                    for (k, b) in row.bytes().enumerate() {
                        if b == b'1' {
                            f.set(x + k as i32, y + r as i32, c);
                        }
                    }
                }
            }
            x += self.w + 1;
        }
        x - 1
    }
}

